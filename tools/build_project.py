def lit(value):
    if isinstance(value,bool): value='true' if value else 'false'
    elif isinstance(value,(int,float)): value=str(value)+'D'
    else:value="'"+str(value).replace("'","''")+"'"
    return {'expr':{'Literal':{'Value':value}}}


def color(value):
    return {'solid':{'color':lit(value)}}


def obj(**props):
    return [{'properties':props}]


def column(t,p):
    return {'Column':{'Expression':{'SourceRef':{'Entity':t}},'Property':p}}


def mexpr(p):
    return {'Measure':{'Expression':{'SourceRef':{'Entity':'MeasuresTable'}},'Property':p}}


def projection(t,p,is_measure=False,label=None):
    v={'field':mexpr(p) if is_measure else column(t,p),'queryRef':t+'.'+p,'nativeQueryRef':label or p}
    if label:v['displayName']=label
    return v


def filter_def(t,p,values):
    return {'Version':2,'From':[{'Name':'s','Entity':t,'Type':0}], 'Where':[{'Condition':{'In':{'Expressions':[{'Column':{'Expression':{'SourceRef':{'Source':'s'}},'Property':p}}], 'Values':[[{'Literal':{'Value':"'"+v.replace("'","''")+"'"}}] for v in values]}}}]}


def filter_config(t,p,values,name):
    return {'filters':[{'name':ident(name),'field':column(t,p),'type':'Categorical','filter':filter_def(t,p,values),'howCreated':'User','isHiddenInViewMode':True,'isLockedInViewMode':True}]}


