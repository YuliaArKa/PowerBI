def uid(text):
    return str(uuid.uuid5(uuid.NAMESPACE_URL, 'labor-market/' + text))


def ident(text):
    return hashlib.sha256(text.encode()).hexdigest()[:20]


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


def write_csv(path, rows, fields):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('w', encoding='utf-8-sig', newline='') as f:
        writer = csv.DictWriter(f, fields)
        writer.writeheader()
        writer.writerows(rows)


def read_csv(path):
    with path.open(encoding='utf-8-sig', newline='') as f:
        return list(csv.DictReader(f))


def normalize():
    graphs = []
    issues = []
    for row in read_csv(DATA / 'source' / 'Labor_Market - GraphTbl.csv'):
        if not row['graph_name'].strip() or not row['page'].strip():
            issues.append(f"{row['graph_id']}: empty graph placeholder retained in original source only.")
            continue
        graphs.append(dict(graph_id=row['graph_id'].strip(), graph_name=row['graph_name'].strip(),
                           index_in_page=int(row['index_in_page']), page=row['page'].strip(),
                           graph_subtitle=row['graph_subtitle'].strip(),
                           graph_kind='KPI' if row['graph_id'].startswith('kpi') else 'Chart'))
    seen = set()
    mappings = []
    sectors = ['A', 'B', 'C', 'D_E', 'F', 'G', 'H', 'I', 'J', 'K', 'L', 'M', 'N', 'O', 'P', 'Q', 'R', 'S']
    vacancy_sectors = ['B_C_D_E', 'F', 'G', 'H', 'I', 'J', 'K', 'L_M_N', 'P', 'Q', 'R_S']
    labels = {
        'UE_R_A25_64_M_SA': 'בלתי מועסקים', 'LF_R_A25_64_M_SA': 'השתתפות',
        'EM_R_A25_64_M_SA': 'תעסוקה', 'EP_M_SA': 'משרות שכיר', 'EM_M_SA': 'מועסקים',
        'LMS_JOB_OPENINGS_TOT_M_SA': 'מספר', 'LMS_JOB_OPENINGS_TOT_PCT_M_SA': 'שיעור',
        'AW_M_SA': 'סה״כ', 'AW_BS_M_SA': 'הסקטור העסקי', 'AW_8_M_SA': 'השירותים הציבוריים',
    }
    graph_ids = {g['graph_id'] for g in graphs}
    for line, row in enumerate(read_csv(DATA / 'source' / 'Labor_Market - SeriesGraphTbl.csv'), start=2):
        graph = row['graph_id'].strip()
        code_list = row['series_code_id'].strip()
        if not graph or not code_list:
            continue
        if graph == 'kpi6':
            graph = 'kpi06'
            issues.append(f'line {line}: normalized kpi6 to kpi06.')
        for code in filter(None, (s.strip() for s in code_list.split(','))):
            target = graph
            if graph == 'g21':
                if 'JOB_OPENINGS' in code: target = 'g24'
                elif '_AW_' in code or code == 'AW_NO_FRN_M_SA': target = 'g22'
                elif '_WT_' in code: target = 'g23'
                if target != graph:
                    issues.append(f'line {line}: routed {code} from g21 to {target} by its metric; original preserved.')
            expansions = [code.replace('<X>', x) for x in (vacancy_sectors if 'JOB_OPENINGS' in code else sectors)] if '<X>' in code else [code]
            for expanded in expansions:
                label = row['series_name_in_graph'].strip()
                if '<X>' in code:
                    label += ' · ' + expanded.replace(code.split('<X>')[0], '').split(code.split('<X>')[1])[0]
                key = (target, expanded, label)
                if key in seen:
                    continue
                seen.add(key)
                transform = 'Raw'
                if target in ['g02', 'g09']: transform = 'YoY_MA3'
                if target == 'g03': transform = 'MA3'
                if target == 'g04' and 'ממוצע' in label: transform = 'MA4Q'
                if target == 'g06' and 'שינוי' in label: transform = 'YoY'
                if target == 'g10': transform = 'YoY_MA3' if 'שינוי' in label else 'MA3'
                if target in ['g17', 'g20'] and 'שינוי' in label: transform = 'YoY_MA3'
                secondary = 'משני' in label
                if target == 'g01': secondary = expanded != 'UE_R_A25_64_M_SA'
                mappings.append(dict(mapping_id=ident('|'.join(key)), graph_id=target,
                    series_code_id=expanded, series_name_in_graph=label,
                    row_label=labels.get(expanded, label) if target.startswith('kpi') else label,
                    series_order=sum(m['graph_id'] == target for m in mappings) + 1,
                    transform=transform, axis='Secondary' if secondary else 'Primary',
                    definition_status='Needs provider verification' if expanded.startswith('LS11_') else 'Mapped'))
    # Match the order of the KPI rows in the reference screenshot.
    orders = {
        'kpi01': ['LF_R_A25_64_M_SA', 'EM_R_A25_64_M_SA', 'UE_R_A25_64_M_SA'],
        'kpi02': ['EM_M_SA', 'EP_M_SA'],
        'kpi03': ['LMS_JOB_OPENINGS_TOT_M_SA', 'LMS_JOB_OPENINGS_TOT_PCT_M_SA'],
        'kpi04': ['AW_BS_M_SA', 'AW_8_M_SA', 'AW_M_SA'],
    }
    for m in mappings:
        order = orders.get(m['graph_id'], [])
        if m['series_code_id'] in order: m['series_order'] = order.index(m['series_code_id']) + 1
    write_csv(DATA / 'GraphTbl.csv', graphs, list(graphs[0]))
    write_csv(DATA / 'SeriesGraphTbl.csv', mappings, list(mappings[0]))
    series = sorted({m['series_code_id'] for m in mappings})
    write_csv(DATA / 'DimSeries.csv', [dict(SERIES_CODE=s) for s in series], ['SERIES_CODE'])
    issues += [f"{g['graph_id']}: no supplied series definition; no series codes have been invented."
               for g in graphs if g['graph_id'] not in {m['graph_id'] for m in mappings}]
    issues += ['Provider-looking LS11_ codes are preserved exactly; verify them before requesting provider data.',
               'CSV descriptions and source labels are reference metadata, not proof of data availability.',
               'Only the four home-page graphs have implemented chart transformations. Other graph transforms are an extensible catalogue, not a completed set of report pages.',
               'No observation data was supplied. observations.csv intentionally contains only a header.']
    (ROOT / 'docs').mkdir(exist_ok=True)
    (ROOT / 'docs' / 'catalogue-notes.md').write_text('# Catalogue normalization\n\n' + '\n'.join('- ' + x for x in issues) + '\n', encoding='utf-8')
    return graphs, mappings


def q(name):
    return "'" + name.replace("'", "''") + "'"


TABLES = {}
MEASURES = {}


def table(name, columns, source, calculated=False, hidden=False, date=False):
    lineage = uid('table/' + name)
    text = f'table {q(name)}\n\tlineageTag: {lineage}\n'
    if hidden: text += '\tisHidden\n'
    if date: text += '\tdataCategory: Time\n'
    for col in columns:
        cname, dtype = col[:2]
        opts = col[2] if len(col) > 2 else {}
        text += f'\n\tcolumn {q(cname)}\n\t\tdataType: {dtype}\n\t\tlineageTag: {uid(name + "/" + cname)}\n'
        if opts.get('hidden'): text += '\t\tisHidden\n'
        if opts.get('key'): text += '\t\tisKey\n'
        if opts.get('format'): text += f'\t\tformatString: {opts["format"]}\n'
        text += '\t\tsummarizeBy: none\n'
        text += f'\t\tsourceColumn: {"[" + cname + "]" if calculated else cname}\n'
        if opts.get('sort'): text += f'\t\tsortByColumn: {q(opts["sort"])}\n'
    text += f'\n\tpartition {q(name)} = {"calculated" if calculated else "m"}\n\t\tmode: import\n\t\tsource =\n'
    text += '\n'.join('\t\t\t' + line if line else '' for line in source.strip().splitlines()) + '\n'
    TABLES[name] = dict(columns={c[0]: c[1] for c in columns}, lineageTag=lineage)
    (MODEL / 'definition' / 'tables').mkdir(parents=True, exist_ok=True)
    (MODEL / 'definition' / 'tables' / (name + '.tmdl')).write_text(text, encoding='utf-8')


def measure(name, expression, fmt=None, folder='General', description=None):
    MEASURES[name] = expression
    p = MODEL / 'definition' / 'tables' / 'MeasuresTable.tmdl'
    with p.open('a', encoding='utf-8') as f:
        f.write('\n')
        if description: f.write('\t/// ' + description + '\n')
        f.write(f'\tmeasure {q(name)} =\n')
        f.write('\n'.join('\t\t\t' + s for s in expression.strip().splitlines()) + '\n')
        if fmt: f.write('\t\tformatString: ' + fmt + '\n')
        f.write('\t\tdisplayFolder: ' + folder + '\n\t\tlineageTag: ' + uid('measure/' + name) + '\n')


def csv_m(file, types):
    t = ', '.join('{"' + c + '", ' + d + '}' for c, d in types)
    return f'''let
    Source = Csv.Document(File.Contents(DataFolder & "/{file}"), [Delimiter=",", Encoding=65001, QuoteStyle=QuoteStyle.Csv]),
    Headers = Table.PromoteHeaders(Source, [PromoteAllScalars=true]),
    Typed = Table.TransformColumnTypes(Headers, {{{t}}}, "en-US")
in
    Typed'''


